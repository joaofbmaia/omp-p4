/**
 * Keep omp's search (grep/glob/find) out of build outputs.
 *
 * omp's walker honours `.ignore` and `.gitignore` but not Perforce's ignore
 * files. P4IGNORE syntax is gitignore syntax, so a generated `.ignore` at the
 * client root that mirrors it makes search skip whatever p4 already skips.
 * Only a `.ignore` carrying {@link GENERATED_HEADER} is ever rewritten.
 */
import * as fs from "node:fs/promises";
import * as path from "node:path";
import { p4 } from "./p4";
import type { Workspace } from "./workspace";

export const GENERATED_HEADER = "# Generated by omp-p4 from";

export type IgnoreState =
	| { kind: "none" } // no P4IGNORE file at the client root
	| { kind: "current" } // .ignore is up to date
	| { kind: "foreign" } // a hand-written .ignore exists; leave it alone
	| { kind: "missing" | "stale"; source: string; target: string };

/** First P4IGNORE file name that exists at the client root (P4IGNORE may list several, `;`-separated). */
async function p4IgnoreFile(ws: Workspace): Promise<string | undefined> {
	// `p4 set -q P4IGNORE` prints `P4IGNORE=<value>` when set, nothing otherwise.
	const set = await p4(["set", "-q", "P4IGNORE"], { cwd: ws.cwd, tagged: false }).catch(() => undefined);
	const value = /^P4IGNORE=(\S+)/m.exec(set?.stdout ?? "")?.[1];
	const names = (value ?? ".p4ignore").split(/[;:]/).filter(n => n && !n.startsWith("~") && !path.isAbsolute(n));
	for (const name of names) {
		const candidate = path.join(ws.root, name);
		if (await fs.stat(candidate).then(s => s.isFile(), () => false)) return candidate;
	}
	return undefined;
}

export async function ignoreState(ws: Workspace): Promise<IgnoreState> {
	const source = await p4IgnoreFile(ws);
	if (!source) return { kind: "none" };
	const target = path.join(ws.root, ".ignore");
	const existing = await fs.readFile(target, "utf8").catch(() => undefined);
	if (existing === undefined) return { kind: "missing", source, target };
	if (!existing.startsWith(GENERATED_HEADER)) return { kind: "foreign" };
	const [srcStat, dstStat] = await Promise.all([fs.stat(source), fs.stat(target)]);
	return srcStat.mtimeMs > dstStat.mtimeMs ? { kind: "stale", source, target } : { kind: "current" };
}

/** Client roots where the user declined the offer, so it is asked once, not every session. */
export async function wasDeclined(stateFile: string, root: string): Promise<boolean> {
	const state = await Bun.file(stateFile).json().catch(() => ({}) as { declinedIgnore?: string[] });
	return (state.declinedIgnore ?? []).includes(root);
}

export async function rememberDecline(stateFile: string, root: string): Promise<void> {
	const state = await Bun.file(stateFile).json().catch(() => ({}) as { declinedIgnore?: string[] });
	state.declinedIgnore = [...new Set([...(state.declinedIgnore ?? []), root])];
	await Bun.write(stateFile, `${JSON.stringify(state, null, 2)}\n`);
}

export async function writeIgnore(source: string, target: string): Promise<void> {
	const body = await fs.readFile(source, "utf8");
	await Bun.write(
		target,
		`${GENERATED_HEADER} ${path.basename(source)}; edit that file instead. Lets omp's search skip what p4 ignores.\n.ignore\n${body}`,
	);
}
